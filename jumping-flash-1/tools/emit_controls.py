"""Emit non-retail fingerprints and instruction-derived JF1 input layouts."""
from pathlib import Path
import json
import struct

ROOT=Path(__file__).resolve().parents[2]
FIELDS=['player','demo_mode','pad_held','move_flags','pitch_target','control_live','original_pause',
        'control_block','finish','finish2','movie','movie_ready']

def fingerprint(words):
    value=14695981039346656037
    for byte in struct.pack('<'+'I'*len(words),*(int(w,16) for w in words)):
        value=((value^byte)*1099511628211)&0xffffffffffffffff
    return value

def emit():
    profiles=json.loads((ROOT/'jumping-flash-1/.workbench/evidence/controls-layouts.json').read_text())['profiles']
    lines=['#pragma once','#include <cstdint>',
           '// Generated by jumping-flash-1/tools/emit_controls.py from verified USA images.',
           'struct Jf1Guard {uint32_t address,words;uint64_t hash;};',
           'struct Jf1Profile {const char* image;uint32_t update,movement,command,camera;',
           '    uint32_t '+','.join(FIELDS)+';Jf1Guard guards[16];};',
           'static constexpr Jf1Profile jf1_profiles[]={']
    for p in profiles:
        update=int(p['functions']['update'],16);movement=int(p['functions']['movement'],16)
        lines.append('    {"'+p['image']+'",'+','.join(f'0x{v:08x}u' for v in [update,movement,movement+0x108,update+0x464])+',')
        lines.append('     '+','.join('0x'+p['fields'][k].lower()+'u' for k in FIELDS)+',{')
        for guard in p['guards'].values():
            lines.append('        {0x'+guard['address'].lower()+f'u,{len(guard["words"])},0x{fingerprint(guard["words"]):016x}ull}},')
        lines.append('    }},')
    lines.append('};')
    sites=set()
    for p in profiles:
        update=int(p['functions']['update'],16);movement=int(p['functions']['movement'],16)
        sites.update([update,movement,movement+0x108,update+0x464])
    lines.append('#include "jf1_control_sites.h"')
    physical=sorted(site&0x1fffffff for site in sites)
    site_lines=['#pragma once','#include <stdint.h>',
        '// Generated from the same verified layouts as jf1_profiles.h. This is a prefilter, not a code-identity guard.',
        'static inline int jf1_control_site(uint32_t address){address&=0x1fffffffu;',
        f'if(address-0x{physical[0]:x}u>0x{physical[-1]-physical[0]:x}u)return 0;',
        'switch(address){']
    site_lines.extend(f'case 0x{site:x}u:' for site in physical)
    site_lines.append('return 1;default:return 0;}}')
    (ROOT/'collection/runtime/jf1_control_sites.h').write_text('\n'.join(site_lines)+'\n')
    output=ROOT/'collection/runtime/jf1_profiles.h';output.write_text('\n'.join(lines)+'\n')
    print(f'Emitted {len(profiles)} exact fingerprint profiles: {output}')

if __name__=='__main__':emit()
