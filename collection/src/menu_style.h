struct GlyphRect { int index, character, left, scale; };
inline ImFont* font(ImFontAtlas* atlas, float size, std::vector<GlyphRect>& rects) {
    ImFontConfig config; config.SizePixels=size; config.OversampleH=config.OversampleV=1;
    config.PixelSnapH=true;
    ImFont* result=atlas->AddFontDefault(&config);
    int scale=std::max(1,int(size/9));
    for(int c=32;c<=126;++c) {
        unsigned mask=0; for(auto row:glyphs[c-32])mask|=row;
        int left=0,right=7;
        if(mask){while(!(mask&(1u<<left)))++left;while(!(mask&(1u<<right)))--right;}
        else right=2;
        int width=right-left+1;
        int index=atlas->AddCustomRectFontGlyph(result,ImWchar(c),width*scale,8*scale,
            (width+1)*scale,ImVec2(0,(size-8*scale)/2));
        rects.push_back({index,c,left,scale});
    }
    return result;
}
inline void rasterize(ImFontAtlas* atlas, const std::vector<GlyphRect>& rects) {
    unsigned char* pixels;int width,height;
    atlas->GetTexDataAsRGBA32(&pixels,&width,&height);
    for(const auto& glyph:rects){
        const auto* rect=atlas->GetCustomRectByIndex(glyph.index);
        IM_ASSERT(rect->IsPacked());
        for(int y=0;y<rect->Height;++y)for(int x=0;x<rect->Width;++x){
            bool ink=glyphs[glyph.character-32][y/glyph.scale]&(1u<<(x/glyph.scale+glyph.left));
            auto* pixel=pixels+4*((rect->Y+y)*width+rect->X+x);
            pixel[0]=pixel[1]=pixel[2]=255;pixel[3]=ink?255:0;
        }
    }
}
